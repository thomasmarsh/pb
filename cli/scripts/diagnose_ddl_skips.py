"""Privacy-safe diagnostic for DDL statement-skip root cause.

Run against a real Oracle DDL dump. Prints ONLY aggregate counts and
keyword-frequency histograms -- never raw statement text, table names, or
column names -- so the output is safe to share even when the DDL file
itself contains sensitive schema/business data.

Parses statement-by-statement (via ddl.py's own `_split_statements`
semicolon/quote/comment-aware splitter) rather than parse_ddl's whole-file
pass, so each raw (pre-constraint-state-stripping) statement string stays
available for keyword search alongside its parse outcome. This matters
because `_strip_constraint_state` deletes ENABLE/DISABLE/USING INDEX from
the text *before* parsing -- scanning only the post-strip rendering (as an
earlier version of this script did) makes any ENABLE/DISABLE-related
failure invisible to the keyword histogram.

Also classifies each skipped statement as catalog-impacting or harmless:
`parse_ddl` only ever extracts columns/PK/FK/CHECK data from CREATE TABLE,
CREATE VIEW, and ALTER TABLE statements containing an ADD CONSTRAINT action
-- a plain CREATE INDEX or an ALTER TABLE with only MODIFY/ENABLE/DISABLE/
RENAME CONSTRAINT actions never feeds the catalog even when it parses
successfully, so its being "skipped" costs nothing. The raw statements_
skipped/statements_total ratio conflates the two; this script reports both.

Usage:
    cd cli && uv run python scripts/diagnose_ddl_skips.py /path/to/real_schema.sql --dialect oracle [--default-namespace SCHEMA]
"""

from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

import sqlglot
from pb.lib.ddl import (
    _detect_hard_wrap_width,
    _dewrap_hard_wrapped_lines,
    _split_statements,
    _strip_constraint_state,
    _strip_view_editioning_clause,
)
from sqlglot import exp
from sqlglot.errors import ErrorLevel, ParseError, TokenError

# Keywords/phrases confirmed (via synthetic reproduction against sqlglot's
# oracle dialect, independent of any customer data) to trip the whole
# containing statement into an opaque exp.Command fallback. Two families:
# physical/storage/segment-attribute tail clauses on CREATE TABLE/INDEX, and
# ALTER TABLE action forms sqlglot's oracle grammar doesn't structurally
# support at all (MODIFY, standalone ENABLE/DISABLE/RENAME CONSTRAINT).
# Matched against the RAW pre-strip statement text -- _strip_constraint_state
# deletes ENABLE/DISABLE/USING INDEX from the text before parsing, so
# searching post-strip text would make those causes invisible.
_KEYWORDS = [
    "STORAGE", "TABLESPACE", "PCTFREE", "PCTUSED", "INITRANS", "MAXTRANS",
    "LOGGING", "NOLOGGING", "PARTITION BY", "SUBPARTITION", "ORGANIZATION INDEX",
    "COMPRESS", "NOCOMPRESS", "CACHE", "NOCACHE", "LOB", "VARRAY",
    "NESTED TABLE", "XMLTYPE", "GENERATED ALWAYS AS", "GENERATED BY DEFAULT",
    "IDENTITY", "SEGMENT CREATION", "PARALLEL", "NOPARALLEL", "MONITORING",
    "NOMONITORING", "PCTINCREASE", "MINEXTENTS", "MAXEXTENTS", "FREELISTS",
    "FREELIST GROUPS", "BUFFER_POOL", "FLASH_CACHE", "RESULT_CACHE",
    "ROWDEPENDENCIES", "NOROWDEPENDENCIES", "INMEMORY", "ENCRYPT",
    "SUPPLEMENTAL LOG", "USING INDEX", "REVERSE", "COMPUTE STATISTICS",
    "VISIBLE", "INVISIBLE", "ONLINE", "UNUSABLE", "DEFAULT ON NULL",
    "BITMAP",
    # ALTER TABLE action forms confirmed unsupported independent of any tail:
    "MODIFY", "ENABLE CONSTRAINT", "DISABLE CONSTRAINT", "RENAME CONSTRAINT",
    "ENABLE ", "DISABLE ",
]

_LEADING_KEYWORD_RE = re.compile(
    r"^\s*(CREATE(?:\s+OR\s+REPLACE)?(?:\s+FORCE)?(?:\s+(?:NON)?EDITIONABLE)?"
    r"\s+(?:GLOBAL\s+TEMPORARY\s+)?(\w+)"
    r"|ALTER\s+(\w+)"
    r"|COMMENT\s+ON\s+(\w+)"
    r"|GRANT\b()"
    r"|DROP\s+(\w+))",
    re.IGNORECASE,
)

_ADD_CONSTRAINT_RE = re.compile(r"\bADD\s+CONSTRAINT\b", re.IGNORECASE)
_INDEX_RE = re.compile(r"^\s*CREATE\s+(?:UNIQUE\s+|BITMAP\s+)?INDEX\b", re.IGNORECASE)


def _find_matching_close_paren(text: str, open_idx: int) -> int | None:
    """Index of the ')' matching text[open_idx] == '(' (quote-aware, so a
    ')' inside a string/quoted-identifier literal isn't miscounted), or
    None if unbalanced."""
    depth = 0
    i = open_idx
    n = len(text)
    in_squote = in_dquote = False
    while i < n:
        c = text[i]
        if in_squote:
            if c == "'":
                if i + 1 < n and text[i + 1] == "'":
                    i += 2
                    continue
                in_squote = False
            i += 1
            continue
        if in_dquote:
            if c == '"':
                in_dquote = False
            i += 1
            continue
        if c == "'":
            in_squote = True
        elif c == '"':
            in_dquote = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return None


def _split_top_level_commas(text: str) -> list[str]:
    """Split text on commas at paren-depth 0 (quote-aware)."""
    elements = []
    buf: list[str] = []
    depth = 0
    in_squote = in_dquote = False
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if in_squote:
            buf.append(c)
            if c == "'":
                if i + 1 < n and text[i + 1] == "'":
                    buf.append(text[i + 1])
                    i += 2
                    continue
                in_squote = False
            i += 1
            continue
        if in_dquote:
            buf.append(c)
            if c == '"':
                in_dquote = False
            i += 1
            continue
        if c == "'":
            in_squote = True
        elif c == '"':
            in_dquote = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if c == "," and depth == 0:
            elements.append("".join(buf).strip())
            buf = []
            i += 1
            continue
        buf.append(c)
        i += 1
    tail = "".join(buf).strip()
    if tail:
        elements.append(tail)
    return elements


def _redact(text: str) -> str:
    """Replace quoted identifiers and string literals with placeholders,
    collapse whitespace. Safe to print: strips every piece of actual
    schema/business content while keeping SQL keywords, types, and
    punctuation, which reveal the syntax shape that's failing."""
    text = re.sub(r'"[^"]+"', "<ID>", text)
    text = re.sub(r"'(?:[^']|'')*'", "<STR>", text)
    return " ".join(text.split())


def _isolate_failing_element(raw_sql: str, dialect: str) -> str | None:
    """For a CREATE TABLE statement confirmed (via `_tail_clause_would_fix`
    returning False) to fail inside its column/constraint list rather than
    on a trailing clause: bisect the top-level comma-separated elements to
    find the first one whose inclusion breaks parsing, and return that one
    element's raw (unredacted) text. Callers must redact before printing.
    Linear scan, not binary search: failure isn't guaranteed monotonic in
    element count (an earlier element could depend on context established
    by this one), so "first k where truncating-to-k fails" is well-defined
    but binary search's monotonicity assumption isn't safe here."""
    open_idx = raw_sql.find("(")
    if open_idx == -1:
        return None
    close_idx = _find_matching_close_paren(raw_sql, open_idx)
    if close_idx is None:
        return None
    header = raw_sql[: open_idx + 1]
    inner = raw_sql[open_idx + 1 : close_idx]
    elements = _split_top_level_commas(inner)
    if not elements:
        return None

    def parses(k: int) -> bool:
        candidate = header + ", ".join(elements[:k]) + ")"
        stripped = _strip_view_editioning_clause(_strip_constraint_state(candidate))
        try:
            parsed = sqlglot.parse(stripped, dialect=dialect, error_level=ErrorLevel.WARN)
        except (ParseError, TokenError):
            return False
        return bool(parsed) and not isinstance(parsed[0], exp.Command)

    for k in range(1, len(elements) + 1):
        if not parses(k):
            return elements[k - 1]
    return None


def _tail_clause_would_fix(raw_sql: str, dialect: str) -> bool | None:
    """For a CREATE TABLE statement, truncate to the closing paren of the
    column/constraint list and re-parse. If the truncated form parses fine,
    the failure is caused entirely by an as-yet-unidentified TRAILING clause
    (the same fixable class as every keyword already stripped in ddl.py) --
    not by anything inside the column/constraint definitions themselves.
    Content-free: reports only True/False/None, never any text. Returns
    None if no top-level "(" is found (shouldn't happen for a real CREATE
    TABLE) or it's unbalanced."""
    open_idx = raw_sql.find("(")
    if open_idx == -1:
        return None
    close_idx = _find_matching_close_paren(raw_sql, open_idx)
    if close_idx is None:
        return None
    truncated = raw_sql[: close_idx + 1]
    stripped = _strip_view_editioning_clause(_strip_constraint_state(truncated))
    try:
        parsed = sqlglot.parse(stripped, dialect=dialect, error_level=ErrorLevel.WARN)
    except (ParseError, TokenError):
        return False
    return bool(parsed) and not isinstance(parsed[0], exp.Command)


def _leading_label(sql: str) -> str:
    m = _LEADING_KEYWORD_RE.match(sql)
    if not m:
        return "(other/none)"
    for g in m.groups()[1:]:
        if g is not None:
            return g.upper() if g else "GRANT"
    return "(other/none)"


def _is_catalog_impacting(label: str, raw_sql: str) -> bool:
    """Mirrors parse_ddl's own consumption rule: only CREATE TABLE, CREATE
    VIEW, and an ALTER TABLE that contains an ADD CONSTRAINT action can ever
    contribute columns/PK/FK/CHECK data to the catalog -- so only losing one
    of THOSE actually loses catalog data. A plain CREATE INDEX or an ALTER
    TABLE with only MODIFY/ENABLE/DISABLE/RENAME CONSTRAINT actions was never
    going to contribute anything regardless of parse outcome."""
    if label == "TABLE" and _INDEX_RE.match(raw_sql):
        return False  # shouldn't happen (INDEX statements label as INDEX/UNIQUE), just in case
    if label in ("VIEW",):
        return True
    if label == "TABLE" and not raw_sql.strip().upper().startswith("ALTER"):
        return True  # CREATE TABLE
    if raw_sql.strip().upper().startswith("ALTER"):
        return bool(_ADD_CONSTRAINT_RE.search(raw_sql))
    return False  # CREATE INDEX / CREATE UNIQUE INDEX / CREATE BITMAP INDEX / other


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("ddl_file")
    ap.add_argument("--dialect", default="oracle")
    ap.add_argument("--default-namespace", default=None, help="accepted for CLI compatibility; unused (doesn't affect parse success/failure)")
    args = ap.parse_args()

    raw_text = Path(args.ddl_file).read_text(errors="replace")

    wrap_width = _detect_hard_wrap_width(raw_text)
    if wrap_width is not None:
        raw_text = _dewrap_hard_wrapped_lines(raw_text, wrap_width)
        print(f"NOTE: detected hard line-wrap at width={wrap_width}, reflowed before analysis")
        print()

    stripped_text = _strip_view_editioning_clause(_strip_constraint_state(raw_text))

    raw_chunks = _split_statements(raw_text)
    stripped_chunks = _split_statements(stripped_text)

    if len(raw_chunks) != len(stripped_chunks):
        print(
            f"NOTE: raw/stripped statement count differs ({len(raw_chunks)} vs "
            f"{len(stripped_chunks)}) -- keyword correlation may be off by a few entries"
        )

    total = len(stripped_chunks)
    parsed_count = 0
    skipped: list[tuple[int, str]] = []  # (index, raw_sql)

    for i, chunk in enumerate(stripped_chunks):
        try:
            parsed = sqlglot.parse(chunk, dialect=args.dialect, error_level=ErrorLevel.WARN)
        except (ParseError, TokenError):
            parsed = []
        is_command = bool(parsed) and isinstance(parsed[0], exp.Command)
        if not parsed or is_command:
            raw = raw_chunks[i] if i < len(raw_chunks) else chunk
            skipped.append((i, raw))
        else:
            parsed_count += 1

    print(f"statements_total={total}")
    print(f"statements_parsed={parsed_count}")
    print(f"statements_skipped={len(skipped)}")
    print(f"skip_rate={len(skipped) / max(total, 1):.1%}")
    print()

    leading_counts: Counter[str] = Counter()
    impact_counts: Counter[str] = Counter()
    keyword_hits: Counter[str] = Counter()
    keyword_hits_impacting: Counter[str] = Counter()
    none_count = 0
    none_count_impacting = 0
    length_stats: list[int] = []
    unexplained_table_impacting: list[str] = []  # raw sql of TABLE-labeled, catalog-impacting, no keyword hit

    for _i, raw in skipped:
        length_stats.append(len(raw))
        label = _leading_label(raw)
        leading_counts[label] += 1
        impacting = _is_catalog_impacting(label, raw)
        impact_counts["catalog-impacting" if impacting else "harmless (never fed catalog)"] += 1

        upper = raw.upper()
        hit_any = False
        for kw in _KEYWORDS:
            if kw in upper:
                keyword_hits[kw] += 1
                hit_any = True
                if impacting:
                    keyword_hits_impacting[kw] += 1
        if not hit_any:
            none_count += 1
            if impacting:
                none_count_impacting += 1
                if label == "TABLE" and not raw.strip().upper().startswith("ALTER"):
                    unexplained_table_impacting.append(raw)

    print("--- skipped statements by leading keyword ---")
    for kw, n in leading_counts.most_common():
        print(f"  {kw}: {n}")

    print()
    print("--- catalog impact of skipped statements ---")
    print("    (only CREATE TABLE / CREATE VIEW / ALTER TABLE...ADD CONSTRAINT can ever")
    print("     contribute columns/PK/FK/CHECK data -- everything else was never captured")
    print("     regardless of whether it parses)")
    for label, n in impact_counts.most_common():
        print(f"  {label}: {n}")

    print()
    print("--- keyword hits, ALL skipped statements (raw pre-strip text) ---")
    for kw, n in keyword_hits.most_common(40):
        print(f"  {kw}: {n}")
    print(f"  matching none: {none_count} / {len(skipped)}")

    print()
    print("--- keyword hits, CATALOG-IMPACTING skipped statements only ---")
    for kw, n in keyword_hits_impacting.most_common(40):
        print(f"  {kw}: {n}")
    print(f"  matching none: {none_count_impacting} / {impact_counts['catalog-impacting']}")

    if length_stats:
        length_stats.sort()
        n = len(length_stats)
        print()
        print("--- full statement length (chars) of skipped statements ---")
        print(f"  min={length_stats[0]} median={length_stats[n // 2]} max={length_stats[-1]}")

    if unexplained_table_impacting:
        print()
        print("--- bisection of unexplained CREATE TABLE losses (content-free) ---")
        print("    Truncates each statement to the closing paren of its column/constraint")
        print("    list and re-parses. 'trailing-clause' means an as-yet-unidentified tail")
        print("    keyword (same fixable class as everything already stripped) is the sole")
        print("    cause; 'inside column/constraint list' means the failure is NOT a tail")
        print("    clause and needs a different kind of fix.")
        outcome_counts: Counter[str] = Counter()
        redacted_patterns: Counter[str] = Counter()
        for raw in unexplained_table_impacting:
            result = _tail_clause_would_fix(raw, args.dialect)
            if result is True:
                outcome_counts["trailing-clause (truncated form parses fine)"] += 1
            elif result is False:
                outcome_counts["inside column/constraint list (still fails when truncated)"] += 1
                element = _isolate_failing_element(raw, args.dialect)
                if element is not None:
                    redacted_patterns[_redact(element)] += 1
                else:
                    outcome_counts["  (bisection couldn't isolate a single element)"] += 1
            else:
                outcome_counts["unbalanced parens / could not bisect"] += 1
        for label, n in outcome_counts.most_common():
            print(f"  {label}: {n}")

        if redacted_patterns:
            print()
            print("--- isolated failing column/constraint definitions, REDACTED ---")
            print("    Every quoted identifier -> <ID>, every string literal -> <STR>.")
            print("    Deduplicated by exact redacted text -- safe to paste back as-is.")
            for pattern, n in redacted_patterns.most_common(20):
                print(f"  x{n}: {pattern}")


if __name__ == "__main__":
    main()
